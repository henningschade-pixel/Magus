const {runBatch}=require('./analyze.js');
const N=+process.argv[2]||4000;
const rules=process.argv[3]?JSON.parse(process.argv[3]):{};
const t0=Date.now();
const o=runBatch(N,rules);
const pct=(a,b)=>b?(100*a/b).toFixed(1)+'%':'-';
const avg=a=>a.reduce((x,y)=>x+y,0)/a.length;
const sorted=o.steps.slice().sort((a,b)=>a-b);
const ci=(p,n)=>(1.96*Math.sqrt(p*(1-p)/n)*100).toFixed(1);
console.log('Partien',o.over,'(festgefahren',o.stuck+')','Dauer',((Date.now()-t0)/1000).toFixed(0)+'s');
const dec=o.first+o.second;
console.log('Beginner siegt',pct(o.first,o.over),'| Zweiter siegt',pct(o.second,o.over),'| Unentschieden',pct(o.draw,o.over));
console.log('  Beginner-Anteil an Entscheidungen',pct(o.first,dec),'±'+ci(o.first/dec,dec),'; mittl. SP-Differenz (Beginner-Zweiter)',(o.spDiffFirst/o.over).toFixed(2));
console.log('Spiellänge (Aktionen/Züge): Median',sorted[sorted.length>>1],'P10',sorted[Math.floor(sorted.length*.1)],'P90',sorted[Math.floor(sorted.length*.9)],'Max',sorted[sorted.length-1]);
console.log('\nShowdowns:');
o.sh.forEach((s,i)=>console.log(` #${i+1}: n=${s.n} Angreifer gewinnt ${pct(s.attWin,s.n)} | Verteidiger ${pct(s.defWin,s.n)} | remis ${pct(s.draw,s.n)} || Beginner ${pct(s.firstWin,s.n)} Zweiter ${pct(s.secondWin,s.n)}`));
console.log('\nMonster (Angriffe, Sieg Spieler / Niederlage / ohne Sieger):');
Object.keys(o.mon).sort().forEach(k=>{const m=o.mon[k];console.log(' '+k.padEnd(22),String(m.att).padStart(5),'Sieg',pct(m.win,m.att).padStart(6),'Niederl.',pct(m.lose,m.att).padStart(6),'ohne',pct(m.none,m.att).padStart(6))});
console.log('\nEndwerte pro Platz (Beginner | Zweiter):');
['maxHpSum','mana','lim','slots','mag','gold','temple'].forEach(k=>console.log(' '+k.padEnd(9),(o.end[k][0]/o.over).toFixed(2),'|',(o.end[k][1]/o.over).toFixed(2)));
console.log('Monsterkills Beginner|Zweiter',o.monsterKills.join(' | '));
require('fs').writeFileSync(process.argv[4]||'/dev/null',JSON.stringify(o));
